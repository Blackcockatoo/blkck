#!/usr/bin/env python3
"""Build responsive AVIF/WebP copies of the site's heavy artwork.

Originals are never touched. Derived files go to opt/<original path stem>-<width>.<ext>
and data/image-manifest.js maps each original to its available widths so the
portal (script.js) and the static pages can emit <picture>/srcset markup.

Run locally after adding artwork:  python3 scripts/optimize-images.py
Needs Pillow >= 11 (AVIF + WebP support). Re-runs skip files that already exist.
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "opt"
WIDTHS = (640, 1280)
MIN_BYTES = 120_000          # small images are already light enough
SCAN = [*ROOT.glob("*.html"), ROOT / "script.js", *ROOT.glob("data/*.js"), *ROOT.glob("*/index.html")]
PATH_RE = re.compile(r"""["'(/]?([A-Za-z0-9_\-./]+?\.(?:png|jpe?g))["')]""", re.I)


def referenced() -> list[str]:
    found: set[str] = set()
    for f in SCAN:
        if not f.exists() or f.name == "image-manifest.js":
            continue
        for m in PATH_RE.finditer(f.read_text(errors="ignore")):
            p = m.group(1).lstrip("./").lstrip("/")
            if p.startswith(("http", "opt/", "share/")):
                continue
            if (ROOT / p).is_file():
                found.add(p)
    return sorted(found)


def main() -> int:
    manifest: dict[str, list] = {}
    made = 0
    for rel in referenced():
        src = ROOT / rel
        if src.stat().st_size < MIN_BYTES:
            continue
        try:
            im = Image.open(src)
            im = ImageOps.exif_transpose(im)
        except Exception as exc:  # pragma: no cover
            print("skip", rel, exc, file=sys.stderr)
            continue
        w, h = im.size
        if im.mode not in ("RGB", "RGBA"):
            im = im.convert("RGBA" if "A" in im.getbands() or im.mode == "P" else "RGB")
        widths = sorted({min(x, w) for x in WIDTHS})
        stem = Path(rel).with_suffix("")
        for tw in widths:
            th = round(h * tw / w)
            frame = None
            for ext, kw in (("avif", {"quality": 55, "speed": 6}), ("webp", {"quality": 80, "method": 5})):
                dest = OUT / f"{stem}-{tw}.{ext}"
                if dest.exists():
                    continue
                if frame is None:
                    frame = im if tw == w else im.resize((tw, th), Image.LANCZOS)
                dest.parent.mkdir(parents=True, exist_ok=True)
                frame.save(dest, **kw)
                made += 1
        manifest[rel] = [w, h, widths]
    js = ("/* Generated by scripts/optimize-images.py — do not edit by hand. */\n"
          "(function (root) {\n  var m = " + json.dumps(manifest, indent=0, sort_keys=True) + ";\n"
          "  if (typeof module !== 'undefined' && module.exports) module.exports = m; else root.BSS_IMAGE_MANIFEST = m;\n"
          "})(typeof window !== 'undefined' ? window : this);\n")
    (ROOT / "data" / "image-manifest.js").write_text(js)
    print(f"{len(manifest)} images in manifest, {made} derived files written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
